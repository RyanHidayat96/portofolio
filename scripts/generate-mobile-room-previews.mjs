import crypto from "node:crypto";
import fs from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputDirectory = path.join(projectRoot, "public", "models", "portfolio-3d", "previews");
const revisionPath = path.join(
  projectRoot,
  "src",
  "features",
  "portfolio-3d",
  "mobile-room-preview-revision.ts"
);
const targetUrl = process.env.PORTFOLIO_PREVIEW_URL ?? "http://127.0.0.1:3000";
const screenIds = [
  "pipeline",
  "automation",
  "performance",
  "backend",
  "terminal",
  "profile",
  "experience",
  "architecture",
  "contact"
];

await fs.mkdir(outputDirectory, { recursive: true });

const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({
  // Match mobile viewport media rules without changing the fixed 1000px
  // embedded-screen coordinate system.
  viewport: { width: 390, height: 844 },
  deviceScaleFactor: 1
});

try {
  page.setDefaultTimeout(60_000);
  await page.goto(targetUrl, { waitUntil: "domcontentloaded" });
  await page.waitForFunction(
    (ids) => ids.every((id) => document.querySelector(`.arcade-screen-document--${id} .arcade-screen-content > *`)),
    screenIds
  );
  await page.evaluate(async () => document.fonts?.ready);

  for (const screenId of screenIds) {
    await page.evaluate((id) => {
      document.querySelector(`[data-mobile-room-preview-capture="${id}"]`)?.remove();
      const source = document.querySelector(`.arcade-screen-document--${id}`);
      if (!(source instanceof HTMLElement)) throw new Error(`Missing ${id} screen.`);

      const width = Number.parseFloat(source.style.width) || 1000;
      const height = Number.parseFloat(source.style.height) || 600;
      const wrapper = document.createElement("div");
      wrapper.dataset.mobileRoomPreviewCapture = id;
      Object.assign(wrapper.style, {
        background: "#0b0703",
        height: `${height}px`,
        left: "0",
        overflow: "hidden",
        pointerEvents: "none",
        position: "fixed",
        top: "0",
        width: `${width}px`,
        zIndex: "2147483647"
      });

      const clone = source.cloneNode(true);
      if (!(clone instanceof HTMLElement)) throw new Error(`Unable to clone ${id} screen.`);
      clone.inert = false;
      clone.removeAttribute("aria-hidden");
      Object.assign(clone.style, {
        display: "block",
        height: `${height}px`,
        left: "0",
        opacity: "1",
        pointerEvents: "none",
        position: "relative",
        top: "0",
        transform: "none",
        visibility: "visible",
        width: `${width}px`
      });
      clone.querySelectorAll("[aria-hidden='true']").forEach((element) => element.removeAttribute("aria-hidden"));
      clone.querySelectorAll("[inert]").forEach((element) => { element.inert = false; });
      wrapper.append(clone);
      document.body.append(wrapper);
    }, screenId);

    const capture = page.locator(`[data-mobile-room-preview-capture="${screenId}"]`);
    await capture.screenshot({
      animations: "disabled",
      path: path.join(outputDirectory, `${screenId}-initial.png`),
      type: "png"
    });
    await page.evaluate((id) => document.querySelector(`[data-mobile-room-preview-capture="${id}"]`)?.remove(), screenId);
    console.log(`Wrote ${screenId}-initial.png`);
  }
} finally {
  await browser.close();
}

const hash = crypto.createHash("sha256");
for (const screenId of screenIds) {
  hash.update(await fs.readFile(path.join(outputDirectory, `${screenId}-initial.png`)));
}
const revision = hash.digest("hex").slice(0, 16);
await fs.writeFile(
  revisionPath,
  [
    "// Generated by scripts/generate-mobile-room-previews.mjs.",
    "// Changes whenever any mobile room preview image changes.",
    `export const mobileRoomPreviewRevision = \"${revision}\";`,
    ""
  ].join("\n")
);
console.log(`Updated mobile preview revision: ${revision}`);
